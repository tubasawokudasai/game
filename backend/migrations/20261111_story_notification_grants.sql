-- ==============================================================================
-- 迁移：剧情通知统一发放内容
--
-- 背景：剧情通知（story_notifications）原先只有标题 / 正文，缺少与玩家升级通知
-- 一致的「发放内容」能力。本迁移为剧情通知资产补充 reward_items_json，
-- 即通知奖励邮件的道具 / 角色 / 货币配置。
--
-- 历史数据默认 '[]'，即只发送即时通知、不创建奖励邮件。
-- ==============================================================================

ALTER TABLE story_notifications
    ADD COLUMN reward_items_json TEXT NOT NULL DEFAULT '[]';
